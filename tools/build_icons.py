"""
Builds static/vendor/octicons.js: the subset of GitHub Primer Octicons (16px) used by the UI.
Run again after adding an icon name to ICONS:  python tools/build_icons.py
"""
import json
import pathlib
import urllib.request

VERSION = "19.41.0"
ICONS = [
    "arrow-left", "arrow-right", "sync", "x", "globe", "lock", "plus", "cursor", "copy", "file", "mortar-board",
    "book", "gear", "sidebar-collapse", "sidebar-expand", "copilot", "play", "square-fill", "sparkle-fill",
    "light-bulb", "rocket", "note", "trash", "paper-airplane", "terminal", "paste", "typography", "search",
    "eye", "eye-closed", "key", "plug", "check", "check-circle-fill", "alert", "alert-fill", "info", "x-circle-fill",
    "checklist", "comment-ai", "unmute", "clock", "sun", "moon", "device-desktop", "list-unordered", "zap",
    "chevron-down", "chevron-right", "screen-full", "mark-github", "hourglass", "tasklist", "dot-fill",
]

OUT = pathlib.Path(__file__).resolve().parents[1] / "static" / "vendor" / "octicons.js"


def main():
    url = f"https://cdn.jsdelivr.net/npm/@primer/octicons@{VERSION}/build/data.json"
    with urllib.request.urlopen(url, timeout=60) as r:
        data = json.loads(r.read().decode())
    icons = {}
    for name in ICONS:
        h16 = data[name]["heights"].get("16") or data[name]["heights"][min(data[name]["heights"], key=int)]
        icons[name] = {"w": h16["width"], "path": h16["path"]}
    OUT.write_text(
        f"/* Primer Octicons v{VERSION} (MIT, github.com/primer/octicons) — subset generated by tools/build_icons.py */\n"
        f"window.OCTICONS = {json.dumps(icons, separators=(',', ':'))};\n",
        encoding="utf-8")
    print(f"wrote {len(icons)} icons to {OUT}")


if __name__ == "__main__":
    main()
